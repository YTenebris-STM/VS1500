#include "stm32f1xx.h"
#include "init.h"

static void INIT_RCC (void)
{
    // Configure system clock to 72 MHz
	
	RCC->CR |= RCC_CR_HSEON;
	while (!(RCC->CR & RCC_CR_HSERDY)) {};

	RCC->CFGR &= (uint32_t)((uint32_t) ~ (RCC_CFGR_PLLSRC |
										RCC_CFGR_PLLXTPRE |
										RCC_CFGR_PLLMULL));
	RCC->CFGR |= RCC_CFGR_PLLSRC | RCC_CFGR_PLLMULL9;
	RCC->CR |= RCC_CR_PLLON;
	while (!(RCC->CR & RCC_CR_PLLRDY)) {};
		
	RCC->CFGR &= ~RCC_CFGR_HPRE;
	RCC->CFGR |=  RCC_CFGR_HPRE_DIV1;
	RCC->CFGR &= ~RCC_CFGR_PPRE1;
	RCC->CFGR |=  RCC_CFGR_PPRE1_DIV2;
	RCC->CFGR &= ~RCC_CFGR_PPRE2;
	RCC->CFGR |=  RCC_CFGR_PPRE2_DIV1;
	RCC->CFGR &= ~RCC_CFGR_ADCPRE;
	RCC->CFGR |=  RCC_CFGR_ADCPRE_DIV6;
		
	FLASH->ACR &= ~FLASH_ACR_PRFTBE;
	FLASH->ACR |=  FLASH_ACR_PRFTBE;
	FLASH->ACR &= ~FLASH_ACR_LATENCY;
	FLASH->ACR |=  FLASH_ACR_LATENCY_2;

	RCC->CFGR &= ~RCC_CFGR_SW;
	RCC->CFGR |=  RCC_CFGR_SW_PLL;
	while (!(RCC->CFGR & RCC_CFGR_SWS_PLL)) {};
}

static void INIT_SPI (void)
{
    RCC->APB2ENR |=  RCC_APB2ENR_IOPAEN | RCC_APB2ENR_IOPBEN | RCC_APB2ENR_SPI1EN | RCC_APB2ENR_AFIOEN;

    GPIOA->CRL |=  GPIO_CRL_MODE7_0; 
    GPIOA->CRL &= ~GPIO_CRL_CNF7_0;
    GPIOA->CRL |=  GPIO_CRL_CNF7_1;
    GPIOA->CRL |=  GPIO_CRL_MODE5_0;
    GPIOA->CRL &= ~GPIO_CRL_CNF5_0;
    GPIOA->CRL |=  GPIO_CRL_CNF5_1;
    GPIOA->CRL |=  GPIO_CRL_MODE4_1;
    GPIOA->CRL &= ~GPIO_CRL_CNF4_0;
    GPIOB->CRL |=  GPIO_CRL_MODE0_1;
    GPIOB->CRL &= ~GPIO_CRL_CNF0_0;

    GPIOA->ODR |=  GPIO_ODR_ODR4;
    GPIOB->ODR &= ~GPIO_ODR_ODR0;

    SPI1->CR1 = 0;
    SPI1->CR2 = 0;
    SPI1->CR1 = SPI_CR1_MSTR | SPI_CR1_SSM | SPI_CR1_SSI | SPI_CR1_BR_2;

    AFIO->EXTICR[0] = AFIO_EXTICR1_EXTI1_PB;
    EXTI->FTSR |= EXTI_FTSR_TR1;
    EXTI->PR = EXTI_PR_PR1;
    EXTI->IMR |= EXTI_IMR_MR1;
    NVIC_EnableIRQ(EXTI1_IRQn);
    NVIC_SetPriority(EXTI1_IRQn, 0);

    SPI1->CR1 |= SPI_CR1_SPE;    
}

static void INIT_TIM4(void)
{
    RCC->APB2ENR |= RCC_APB2ENR_IOPBEN;
    RCC->APB1ENR |= RCC_APB1ENR_TIM4EN;
    
    GPIOB->CRL |= GPIO_CRL_MODE6_1 | GPIO_CRL_CNF6_1 |
                  GPIO_CRL_MODE7_1 | GPIO_CRL_CNF7_1;
    
    GPIOB->CRL &= ~GPIO_CRL_CNF6_0;
    GPIOB->CRL &= ~GPIO_CRL_CNF7_0;

    TIM4->CR1 = 0;
    TIM4->PSC = 0;
    TIM4->ARR = 3599;

    TIM4->CCMR1 =
        TIM_CCMR1_OC1M_1 | TIM_CCMR1_OC1M_2 |
        TIM_CCMR1_OC1PE | TIM_CCMR1_OC2M_1 | 
        TIM_CCMR1_OC2M_2 | TIM_CCMR1_OC2PE;

    TIM4->CCR1 = 0;
    TIM4->CCR2 = 0;

    TIM4->CCER = TIM_CCER_CC1E | TIM_CCER_CC2E;
    TIM4->CR1 |= TIM_CR1_ARPE;

    TIM4->EGR = TIM_EGR_UG;
    TIM4->SR &= ~TIM_SR_UIF;

    TIM4->CR1 |= TIM_CR1_CEN;
}

static void INIT_TIM2 (void)
{
    RCC->APB2ENR |= RCC_APB2ENR_AFIOEN | RCC_APB2ENR_IOPBEN;
    RCC->APB1ENR |= RCC_APB1ENR_TIM2EN;

    AFIO->MAPR = (AFIO->MAPR & ~AFIO_MAPR_TIM2_REMAP) |
                 AFIO_MAPR_TIM2_REMAP_PARTIALREMAP2;

    GPIOB->CRH |= GPIO_CRH_MODE11_1 | GPIO_CRH_CNF11_1;
    GPIOB->CRH &= ~GPIO_CRH_CNF11_0;

    TIM2->PSC = 71;
    TIM2->ARR = 19999;

    TIM2->CCMR2 =
        (TIM2->CCMR2 & ~(TIM_CCMR2_CC4S | TIM_CCMR2_OC4M)) |
        TIM_CCMR2_OC4M_1 | TIM_CCMR2_OC4M_2 | TIM_CCMR2_OC4PE;

    TIM2->CCR4 = 1000;
    TIM2->CCER |= TIM_CCER_CC4E;
    TIM2->CR1 |= TIM_CR1_ARPE;

    TIM2->EGR = TIM_EGR_UG;
    TIM2->SR &= ~TIM_SR_UIF;

    TIM2->CR1 |= TIM_CR1_CEN;
}

void INIT_System (void)
{
    INIT_RCC();
    INIT_SPI();
    INIT_TIM2();
    INIT_TIM4();
}